// Known-answer vectors for the classic OpenVPN key-method-2 key derivation —
// the only test here that can tell a correct PRF from a convincing wrong one.
//
// testdata/vectors.json was captured from a real OpenVPN 2.4.12 peer: an
// instrumented build dumps the inputs and output of generate_key_expansion()
// (src/openvpn/ssl.c), and two containers of it complete a handshake so the two
// dumps can be compared. See docker/PRF-VECTORS.md.
package prf_test

import (
	"bytes"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"testing"

	"github.com/buengese/go-openvpn/internal/prf"
)

// vectorsPath is the captured ground truth, relative to this package.
const vectorsPath = "testdata/vectors.json"

// vectorFile is testdata/vectors.json.
type vectorFile struct {
	Provenance struct {
		CapturedAt           string   `json:"captured_at"`
		OpenVPNVersion       string   `json:"openvpn_version"`
		Image                string   `json:"image"`
		Patch                string   `json:"patch"`
		InstrumentedFunction string   `json:"instrumented_function"`
		Derivation           []string `json:"derivation"`
	} `json:"provenance"`
	Vectors []vector `json:"vectors"`
}

// vector is one captured handshake: everything the two-stage derivation
// consumed, and the 256-byte key block it produced.
type vector struct {
	Name   string `json:"name"`
	Cipher string `json:"cipher"`
	Digest string `json:"digest"`
	Proto  string `json:"proto"`

	// Client material. PreMaster is generated by the client only; the
	// server's own key_source carries no pre_master (OpenVPN 2.4
	// src/openvpn/ssl.c, key_source2_randomize_write()).
	ClientPreMaster string `json:"client_pre_master"`
	ClientRandom1   string `json:"client_random1"`
	ClientRandom2   string `json:"client_random2"`

	// Server material.
	ServerRandom1 string `json:"server_random1"`
	ServerRandom2 string `json:"server_random2"`

	// The two 8-byte control-channel session IDs, which seed stage two.
	ClientSessionID string `json:"client_session_id"`
	ServerSessionID string `json:"server_session_id"`

	// MasterSecret is the 48-byte stage-one output. It is recorded so a
	// failure can be localised to one stage rather than to "the PRF".
	MasterSecret string `json:"master_secret"`

	// KeyBlock is the 256-byte stage-two output: the four 64-byte slots
	// described in prf.Slots, in order.
	KeyBlock string `json:"key_block"`
}

// loadVectors reads and decodes testdata/vectors.json.
func loadVectors(t *testing.T) vectorFile {
	t.Helper()
	raw, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatalf("read %s: %v", vectorsPath, err)
	}
	var vf vectorFile
	if err := json.Unmarshal(raw, &vf); err != nil {
		t.Fatalf("decode %s: %v", vectorsPath, err)
	}
	if len(vf.Vectors) == 0 {
		t.Fatalf("%s contains no vectors", vectorsPath)
	}
	return vf
}

// mustHex decodes a hex field and asserts its decoded length.
func mustHex(t *testing.T, field, s string, want int) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatalf("%s: not hex: %v", field, err)
	}
	if len(b) != want {
		t.Fatalf("%s: %d bytes, want %d", field, len(b), want)
	}
	return b
}

// vectorInputs decodes one vector into the arguments the real API takes.
//
// PreMaster is set on the client alone, matching what the peers exchange: the
// server's key_source2 carries randoms only (OpenVPN 2.4 src/openvpn/ssl.c,
// key_source2_randomize_write()).
func vectorInputs(t *testing.T, v vector) (client, server prf.KeySource, clientSID, serverSID []byte) {
	t.Helper()
	client = prf.KeySource{
		PreMaster: mustHex(t, "client_pre_master", v.ClientPreMaster, 48),
		Random1:   mustHex(t, "client_random1", v.ClientRandom1, 32),
		Random2:   mustHex(t, "client_random2", v.ClientRandom2, 32),
	}
	server = prf.KeySource{
		Random1: mustHex(t, "server_random1", v.ServerRandom1, 32),
		Random2: mustHex(t, "server_random2", v.ServerRandom2, 32),
	}
	clientSID = mustHex(t, "client_session_id", v.ClientSessionID, 8)
	serverSID = mustHex(t, "server_session_id", v.ServerSessionID, 8)
	return client, server, clientSID, serverSID
}

// describeDiff summarises how a derived value differs from the recorded one:
// where it first diverges, how much diverges, and — for a 256-byte key block —
// which 64-byte slot the first difference lands in. A block wrong only in slots
// 2 and 3 is a different bug from one wrong from byte 0.
func describeDiff(got, want []byte) string {
	if len(got) != len(want) {
		return fmt.Sprintf("length %d, want %d", len(got), len(want))
	}
	first, differing := -1, 0
	for i := range want {
		if got[i] != want[i] {
			if first < 0 {
				first = i
			}
			differing++
		}
	}
	if first < 0 {
		return "identical"
	}
	s := fmt.Sprintf("%d of %d bytes differ, first at offset %d", differing, len(want), first)
	if len(want) == 256 {
		s += fmt.Sprintf(" (slot %d, byte %d within it)", first/64, first%64)
	}
	return s
}

