// TestKeyMethod2Vectors checks both stages of the derivation against ground
// truth captured from a real OpenVPN 2.4.12 peer. Each vector runs as two
// nested subtests so a failure names its stage, which is why master_secret is
// recorded at all: stage one diverging points at the PRF or its seed, while
// stage one passing and stage two failing narrows it to the second label, the
// second pair of randoms, or the session IDs.
func TestKeyMethod2Vectors(t *testing.T) {
	vf := loadVectors(t)
	for _, v := range vf.Vectors {
		t.Run(v.Name, func(t *testing.T) {
			client, server, clientSID, serverSID := vectorInputs(t, v)

			// Stage one: master = TLS1PRF(pre_master, "OpenVPN master
			// secret", client_random1 ‖ server_random1) -> 48 B.
			stageOneOK := t.Run("stage1_master_secret", func(t *testing.T) {
				want := mustHex(t, "master_secret", v.MasterSecret, 48)
				got, err := prf.DeriveMasterSecret(client, server)
				if err != nil {
					t.Fatalf("DeriveMasterSecret: %v", err)
				}
				if !bytes.Equal(got, want) {
					t.Fatalf("stage 1 diverged from OpenVPN %s: %s\n"+
						"  suspect the PRF itself (TLS 1.0 MD5+SHA1 split, not HMAC-SHA256 and\n"+
						"  not the TLS 1.2 PRF), the label \"OpenVPN master secret\", or the order\n"+
						"  of client_random1 ‖ server_random1\n"+
						"   got: %x\n  want: %x",
						vf.Provenance.OpenVPNVersion, describeDiff(got, want), got, want)
				}
			})

			// Stage two: key_block = TLS1PRF(master, "OpenVPN key expansion",
			// client_random2 ‖ server_random2 ‖ client_sid ‖ server_sid) -> 256 B.
			t.Run("stage2_key_block", func(t *testing.T) {
				if !stageOneOK {
					t.Skip("not evaluated: stage 1 already diverged and stage 2 " +
						"consumes its output — fix the master secret first")
				}
				want := mustHex(t, "key_block", v.KeyBlock, 256)
				got, err := prf.DeriveKeyBlock(client, server, clientSID, serverSID)
				if err != nil {
					t.Fatalf("DeriveKeyBlock: %v", err)
				}
				if !bytes.Equal(got, want) {
					t.Fatalf("stage 2 diverged (cipher=%s digest=%s proto=%s, captured from OpenVPN %s): %s\n"+
						"  stage 1 matched, so the PRF and the master secret are right;\n"+
						"  suspect the label \"OpenVPN key expansion\", the order of\n"+
						"  client_random2 ‖ server_random2, or the two 8-byte session IDs\n"+
						"  appended after them\n"+
						"   got: %x\n  want: %x",
						v.Cipher, v.Digest, v.Proto, vf.Provenance.OpenVPNVersion,
						describeDiff(got, want), got, want)
				}
			})
		})
	}
}

// TestVectorsAreWellFormed guards the captured testdata itself: it must stay
// loadable, correctly sized, and wide enough to be worth trusting. The floor —
// at least three vectors across at least two cipher/digest combinations — is
// enforced so that an edit cannot quietly narrow the ground truth.
func TestVectorsAreWellFormed(t *testing.T) {
	vf := loadVectors(t)

	if len(vf.Vectors) < 3 {
		t.Errorf("%d vectors, want at least 3", len(vf.Vectors))
	}
	if vf.Provenance.OpenVPNVersion == "" || vf.Provenance.Patch == "" ||
		vf.Provenance.Image == "" || vf.Provenance.CapturedAt == "" {
		t.Error("provenance is incomplete; a vector nobody can regenerate is not ground truth")
	}
	if len(vf.Provenance.Derivation) == 0 {
		t.Error("provenance records no derivation description")
	}

	combos := make(map[string]bool)
	blocks := make(map[string]string)
	for _, v := range vf.Vectors {
		t.Run(v.Name, func(t *testing.T) {
			mustHex(t, "client_pre_master", v.ClientPreMaster, 48)
			mustHex(t, "client_random1", v.ClientRandom1, 32)
			mustHex(t, "client_random2", v.ClientRandom2, 32)
			mustHex(t, "server_random1", v.ServerRandom1, 32)
			mustHex(t, "server_random2", v.ServerRandom2, 32)
			mustHex(t, "client_session_id", v.ClientSessionID, 8)
			mustHex(t, "server_session_id", v.ServerSessionID, 8)
			mustHex(t, "master_secret", v.MasterSecret, 48)
			mustHex(t, "key_block", v.KeyBlock, 256)

			if v.Cipher == "" || v.Digest == "" {
				t.Error("vector records no cipher/digest")
			}
		})
		combos[v.Cipher+"/"+v.Digest] = true
		if prev, dup := blocks[v.KeyBlock]; dup {
			t.Errorf("%s and %s recorded the same key block; ephemeral material must differ per handshake",
				prev, v.Name)
		}
		blocks[v.KeyBlock] = v.Name
	}

	if len(combos) < 2 {
		t.Errorf("%d cipher/digest combination(s), want at least 2", len(combos))
	}
}
